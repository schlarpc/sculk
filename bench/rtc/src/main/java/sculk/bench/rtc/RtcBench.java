package sculk.bench.rtc;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Constructor;
import java.nio.charset.StandardCharsets;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import sculk.shaded.com.dylibso.chicory.runtime.ImportValues;
import sculk.shaded.com.dylibso.chicory.runtime.Instance;
import sculk.shaded.com.dylibso.chicory.runtime.Machine;
import sculk.shaded.com.dylibso.chicory.wasi.WasiExitException;
import sculk.shaded.com.dylibso.chicory.wasi.WasiOptions;
import sculk.shaded.com.dylibso.chicory.wasi.WasiPreview1;
import sculk.shaded.com.dylibso.chicory.wasm.Parser;
import sculk.shaded.com.dylibso.chicory.wasm.WasmModule;

/**
 * Runs rust/rtc-bench (two str0m peers and a data channel) under Chicory.
 *
 * <p>{@code --mode interp|aot} (default aot), {@code --runs n} (default 3: the
 * first includes the JVM's own warm-up), and the rest is passed to the wasm
 * ({@code --mb}, {@code --msg}). Each run is a fresh instance; the module is
 * parsed once, as the mod would.
 */
public final class RtcBench {
    public static void main(String[] args) throws Exception {
        String mode = "aot";
        int runs = 3;
        List<String> wasmArgs = new ArrayList<>(List.of("rtc-bench"));
        for (int i = 0; i < args.length; i++) {
            switch (args[i]) {
                case "--mode" -> mode = args[++i];
                case "--runs" -> runs = Integer.parseInt(args[++i]);
                default -> wasmArgs.add(args[i]);
            }
        }

        long t = System.nanoTime();
        WasmModule module;
        try (InputStream in = RtcBench.class.getResourceAsStream("rtc-bench.wasm")) {
            module = Parser.parse(in);
        }
        System.out.printf("java=%s mode=%s parse_ms=%.1f%n",
                Runtime.version(), mode, (System.nanoTime() - t) / 1e6);

        Function<Instance, Machine> machine = switch (mode) {
            case "interp" -> null; // Chicory's default: the interpreter
            case "aot" -> aotMachine();
            default -> throw new IllegalArgumentException("--mode interp|aot");
        };

        for (int run = 1; run <= runs; run++) {
            Map<String, String> r = runOnce(module, machine, wasmArgs);
            System.out.printf("run %d: setup %s ms, handshake %s ms (cpu L %s / R %s), "
                            + "%s MB in %s ms: sender %s MB/s, receiver %s MB/s%n",
                    run, r.get("setup_ms"), r.get("handshake_ms"),
                    r.get("handshake_left_cpu_ms"), r.get("handshake_right_cpu_ms"),
                    r.get("transfer_mb"), r.get("transfer_ms"),
                    r.get("sender_mb_per_s"), r.get("receiver_mb_per_s"));
        }
    }

    @SuppressWarnings("unchecked")
    private static Function<Instance, Machine> aotMachine() throws ReflectiveOperationException {
        // Generated by the aotCompile task; loaded by name so this compiles without it.
        Constructor<? extends Machine> c = (Constructor<? extends Machine>)
                Class.forName("sculk.bench.rtc.RtcBenchMachine").getConstructor(Instance.class);
        return instance -> {
            try {
                return c.newInstance(instance);
            } catch (ReflectiveOperationException e) {
                throw new IllegalStateException(e);
            }
        };
    }

    private static Map<String, String> runOnce(
            WasmModule module, Function<Instance, Machine> machine, List<String> args) throws IOException {
        var stdout = new ByteArrayOutputStream();
        var options = WasiOptions.builder()
                .withArguments(args)
                .withStdout(stdout)
                .withStderr(System.err)
                .withRandom(new SecureRandom())
                .build();
        int exit = 0;
        try (var wasi = WasiPreview1.builder().withOptions(options).build()) {
            var builder = Instance.builder(module)
                    .withImportValues(ImportValues.builder().addFunction(wasi.toHostFunctions()).build())
                    .withStart(false);
            if (machine != null) {
                builder.withMachineFactory(machine);
            }
            Instance instance = builder.build();
            try {
                instance.export("_start").apply();
            } catch (WasiExitException e) {
                exit = e.exitCode();
            }
        }
        String out = stdout.toString(StandardCharsets.UTF_8);
        if (exit != 0) {
            throw new IllegalStateException("rtc-bench exited with " + exit + ":\n" + out);
        }
        Map<String, String> result = new LinkedHashMap<>();
        for (String line : out.split("\n")) {
            int eq = line.indexOf('=');
            if (eq > 0) result.put(line.substring(0, eq), line.substring(eq + 1));
        }
        return result;
    }
}
